let currentLang = localStorage.getItem('preferredLanguage') || 'ru';


document.addEventListener('DOMContentLoaded', function() {

    setActiveLanguage(currentLang);
    updateContent(currentLang);
    

    setTimeout(() => {
        document.documentElement.classList.add('loaded');
        document.body.classList.add('loaded');
    }, 100);

    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            
            const targetId = this.getAttribute('href');
            if (targetId === '#') return;
            
            const targetElement = document.querySelector(targetId);
            if (targetElement) {
                window.scrollTo({
                    top: targetElement.offsetTop - 80,
                    behavior: 'smooth'
                });
                

                history.pushState(null, null, targetId);
            }
        });
    });
    

    const sections = document.querySelectorAll('section');
    const navLinks = document.querySelectorAll('.nav-links a');
    
    function updateActiveNav() {
        let current = '';
        
        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.clientHeight;
            
            if (pageYOffset >= (sectionTop - sectionHeight / 3)) {
                current = '#' + section.getAttribute('id');
            }
        });
        
        navLinks.forEach(link => {
            link.classList.remove('active');
            if (link.getAttribute('href') === current) {
                link.classList.add('active');
            }
        });
    }
    

    updateActiveNav();
    

    window.addEventListener('scroll', updateActiveNav);
    
    const contactForm = document.querySelector('.contact-form');
    if (contactForm) {
        contactForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            const formData = new FormData(this);
            const formValues = Object.fromEntries(formData.entries());
            
            console.log('Form submitted:', formValues);
            
            alert('Спасибо за ваше сообщение! Мы свяжемся с вами в ближайшее время.');
            
            this.reset();
        });
    }
    
    const animateOnScroll = function() {
        const elements = document.querySelectorAll('.service-card, .team-member, .stat-item');
        
        elements.forEach(element => {
            const elementPosition = element.getBoundingClientRect().top;
            const screenPosition = window.innerHeight / 1.3;
            
            if (elementPosition < screenPosition) {
                element.style.opacity = '1';
                element.style.transform = 'translateY(0)';
            }
        });
    };
    
    document.querySelectorAll('.service-card, .team-member, .stat-item').forEach(element => {
        element.style.opacity = '0';
        element.style.transform = 'translateY(20px)';
        element.style.transition = 'opacity 0.6s ease-out, transform 0.6s ease-out';
    });
    
    animateOnScroll();
    
    window.addEventListener('scroll', animateOnScroll);
    
    function setActiveLanguage(lang) {
        const langButtons = document.querySelectorAll('.lang-btn');
        langButtons.forEach(btn => {
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
        
        localStorage.setItem('preferredLanguage', lang);
        currentLang = lang;
    }
    
    const langButtons = document.querySelectorAll('.lang-btn');
    
    langButtons.forEach(button => {
        button.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            if (lang !== currentLang) {
                const scrollPosition = window.scrollY || document.documentElement.scrollTop;
                
                setActiveLanguage(lang);
                
                updateContent(lang);
                
                requestAnimationFrame(() => {
                    window.scrollTo(0, scrollPosition);
                });
            }
        });
    });

    function updateContent(lang) {
        document.title = `The Saint Group - ${lang === 'ru' ? 'Команда разработчиков из Санкт-Петербурга' : 'Development Team from Saint Petersburg'}`;
        
        document.querySelectorAll('[data-translate]').forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[lang] && translations[lang][key]) {
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    element.placeholder = translations[lang][key];
                } 
                else if (element.tagName === 'BUTTON') {
                    element.textContent = translations[lang][key];
                }
                else {
                    element.textContent = translations[lang][key];
                }
            }
        });
        
        document.querySelectorAll('.position-meta span:first-child').forEach(span => {
            if (lang === 'en') {
                span.innerHTML = span.innerHTML
                    .replace('Опыт', 'Experience')
                    .replace('года', 'years')
                    .replace('год', 'year');
            } else {
                span.innerHTML = span.innerHTML
                    .replace('Experience', 'Опыт')
                    .replace('years', 'года')
                    .replace('year', 'год');
            }
        });
    }
});
